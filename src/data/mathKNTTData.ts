// Helper to extract all questions for a given grade or the entire KNTT curriculum
export const getAllMathKNTTQuestions = (grade?: 10 | 11 | 12): Question[] => {
  const result: Question[] = [];
  const gradesToInclude = grade
    ? MATH_KNTT_DATA.filter((g) => g.grade === grade)
    : MATH_KNTT_DATA;

  let qNumber = 1;
  gradesToInclude.forEach((g) => {
    g.chapters.forEach((c) => {
      c.lessons.forEach((l) => {
        l.questions.forEach((q) => {
          const celestial = CELESTIAL_LIST[(qNumber - 1) % CELESTIAL_LIST.length];
          result.push({
            ...q,
            number: qNumber,
            planetName: celestial.name,
            planetType: celestial.type,
            isAnswered: false,
          });
          qNumber++;
        });
      });
    });
  });

  return result;
};

// Helper to get questions filtered by grade, chapter, lesson
export const getFilteredMathQuestions = (
  grade?: 10 | 11 | 12,
  chapterId?: string,
  lessonId?: string
): Question[] => {
  const result: Question[] = [];
  const gradesToInclude = grade
    ? MATH_KNTT_DATA.filter((g) => g.grade === grade)
    : MATH_KNTT_DATA;

  let count = 1;
  for (const g of gradesToInclude) {
    for (const c of g.chapters) {
      if (chapterId && c.id !== chapterId) continue;
      for (const l of c.lessons) {
        if (lessonId && l.id !== lessonId) continue;
        for (const q of l.questions) {
          const celestial = CELESTIAL_LIST[(count - 1) % CELESTIAL_LIST.length];
          result.push({
            ...q,
            number: count,
            planetName: celestial.name,
            planetType: celestial.type,
            isAnswered: false,
          });
          count++;
        }
      }
    }
  }

  return result;
};
